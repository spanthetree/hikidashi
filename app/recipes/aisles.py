OTHER = "other"
ORDER = (*AISLES, OTHER)

_TERMS = sorted(
    ((t, aisle) for aisle, terms in AISLES.items() for t in terms), key=lambda ta: -len(ta[0])
)
_PATTERN = re.compile(r"\b(?:" + "|".join(re.escape(t) for t, _ in _TERMS) + r")(?:e?s)?\b")
_AISLE_OF = {t: a for t, a in _TERMS}

# Words that put a thing in a different aisle from its name's: canned
# tomatoes are not with the fresh ones.
_FORCE = (("canned", "pantry"), ("tinned", "pantry"), ("frozen", "frozen"))


def _term(found: str) -> str:
    """The list's own spelling of a match that may carry a plural ending."""
    for cut in (0, 1, 2):
        stem = found[: len(found) - cut] if cut else found
        if stem in _AISLE_OF:
            return stem
    return found


@functools.lru_cache(maxsize=4096)
def aisle_of(item: str) -> str:
    """The aisle an ingredient is in, or OTHER."""
    text = normalise(item)
    words = text.split()
    for word, aisle in _FORCE:
        if word in words:
            return aisle
    best: tuple[bool, int, str] | None = None
    # Every word is a place a match may start: "chicken broth" must try
    # "broth" as well as "chicken".
    for start in range(len(text)):
        if start and text[start - 1] != " ":
            continue
        m = _PATTERN.match(text, start)
        if not m:
            continue
        term = _term(m[0])
        ends = m.end() == len(text)
        key = (ends, len(term), _AISLE_OF[term])
        if best is None or key[:2] > best[:2]:
            best = key
    return best[2] if best else OTHER


_STAPLES = (
    r"(?:(?:kosher|sea|table|fine|coarse|flaky|flaked) )?salt",
    r"(?:(?:freshly )?(?:ground|cracked) )?(?:black )?pepper(?:corns?)?",
    r"salt (?:and )?pepper",  # "&" is gone by now
    r"(?:(?:cold|warm|hot|boiling|ice|tap|lukewarm) )?water",
    r"ice(?: cubes?)?",
    r"(?:(?:extra virgin|light) )?(?:olive|vegetable|canola|neutral|sunflower|cooking|"
    r"rapeseed|frying) oil|oil",
)
_STAPLE = re.compile(r"(?:" + "|".join(_STAPLES) + r")")


@functools.lru_cache(maxsize=4096)
def is_staple(item: str) -> bool:
    """Salt, pepper, cooking oil, water: already in the kitchen."""
    return bool(_STAPLE.fullmatch(normalise(item)))
